"""Bundle the pinned local G6 distribution and application without npm."""
from pathlib import Path

HERE = Path(__file__).resolve().parent


def build():
    static = HERE / 'static'
    vendor = static / 'vendor/g6-5.1.1.min.js'
    application = static / 'workbench.js'
    output = static / 'app.js'
    content = ('/* Generated by build_ui.py. Edit static/workbench.js. '
               'G6 5.1.1: MIT; see static/vendor/G6-LICENSE.txt. */\n'
               + vendor.read_text(encoding='utf-8')
               + '\n;\n' + application.read_text(encoding='utf-8'))
    output.write_text(content, encoding='utf-8')
    print(f'Built {output.name}: {output.stat().st_size:,} bytes')


if __name__ == '__main__':
    build()
